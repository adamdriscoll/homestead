import { resolve } from 'node:path';
import { repoRoot } from '../support/docker.mjs';
import { test, expect, newPost, saved, publish } from '../support/fixtures.mjs';

test('guide supplies, step Markdown, inline photos and durations survive autosave and reordering', async ({ owner: page, browser, site }) => {
  await newPost(page, 'guide');
  await page.getByLabel('Title (required to publish)', { exact: true }).fill('Browser bread');
  await page.getByLabel('Introduction', { exact: true }).fill('A bread recipe.');
  await expect(page.locator('#editor-tools')).toBeHidden();
  await expect(page.locator('#editor-materials')).toBeHidden();
  await page.getByRole('tab', { name: 'Tools', exact: true }).click();
  await expect(page.locator('#editor-write')).toBeHidden();
  await page.getByRole('button', { name: 'Add tool', exact: true }).click();
  await page.getByLabel('Tool 1 name (required to publish)', { exact: true }).fill('Mixing bowl');
  await page.getByLabel('Tool 1 link', { exact: true }).fill('https://example.test/bowl');
  await page.getByRole('button', { name: 'Add tool', exact: true }).click();
  await page.getByLabel('Tool 2 name (required to publish)', { exact: true }).fill('Spoon');
  await page.getByRole('button', { name: 'Move tool up', exact: true }).nth(1).click();
  await expect(page.getByLabel('Tool 1 name (required to publish)', { exact: true })).toHaveValue('Spoon');
  await page.getByRole('button', { name: 'Remove tool', exact: true }).nth(0).click();
  await page.getByRole('tab', { name: 'Tools', exact: true }).focus();
  await page.keyboard.press('ArrowRight');
  await expect(page.getByRole('tab', { name: 'Materials', exact: true })).toHaveAttribute('aria-selected', 'true');
  await page.getByRole('button', { name: 'Add material', exact: true }).click();
  await page.getByLabel('Material 1 name (required to publish)', { exact: true }).fill('2 cups flour');
  const quantity = page.getByLabel('Material 1 quantity', { exact: true });
  await expect(quantity).toHaveAttribute('type', 'text');
  await quantity.fill('10 boxes');
  await page.getByLabel('Material 1 link', { exact: true }).fill('https://example.test/flour');
  await expect(page.locator('#editor-materials')).not.toContainText('optional');
  await expect(page.locator('#editor-materials label').filter({ hasText: 'Material 1 name' }).locator('use')).toHaveAttribute('href', '/icons/toolbar.svg#asterisk');
  await page.getByRole('tab', { name: 'Write', exact: true }).click();
  await page.getByRole('button', { name: 'Add step', exact: true }).click();
  await page.getByLabel('Step 1 title', { exact: true }).fill('Mix ingredients');
  const first = page.getByRole('textbox', { name: 'Step 1 instructions (required to publish)', exact: true });
  await first.fill('Mix ingredients.');
  await expect(page.getByLabel('Step 1 duration', { exact: true })).toHaveAttribute('type', 'time');
  await expect(page.locator('#article-editor input[name$=".DurationDays"]')).toHaveCount(0);
  await page.getByLabel('Step 1 duration', { exact: true }).fill('01:30:00');
  await page.locator('[data-guide-step] summary').nth(0).click();
  await expect(first).toBeHidden();
  await expect(page.locator('[data-guide-step] summary').nth(0)).toHaveText('Step 1 — Mix ingredients');
  await page.getByRole('button', { name: 'Add step', exact: true }).click();
  await expect(page.locator('[data-guide-step]').nth(0)).not.toHaveAttribute('open', '');
  await page.getByLabel('Step 2 title', { exact: true }).fill('Bake bread');
  const second = page.getByRole('textbox', { name: 'Step 2 instructions (required to publish)', exact: true });
  await second.fill('Bake.');
  // A toolbar must target its own editor even when the introduction was focused last.
  await page.getByLabel('Introduction', { exact: true }).focus();
  const toolbar = page.getByRole('group', { name: 'Step 2 Markdown formatting', exact: true });
  await toolbar.getByRole('button', { name: 'Bold (Ctrl/⌘+B)', exact: true }).click();
  await expect(second).toHaveValue('Bake.**bold text**');
  await expect(page.getByLabel('Introduction', { exact: true })).toHaveValue('A bread recipe.');
  const picker = page.waitForEvent('filechooser');
  await toolbar.getByRole('button', { name: 'Upload and insert image', exact: true }).click();
  await (await picker).setFiles(resolve(repoRoot, 'src/Homestead/wwwroot/icon-192.png'));
  await expect(page.locator('#inline-upload-status')).toHaveText('Uploaded and inserted into the draft.');
  await saved(page);
  const mediaPath = (await second.inputValue()).match(/\]\((\/media\/[^)]+)\)/)[1];
  await page.locator('[data-guide-step]').nth(1).getByRole('button', { name: 'Move step up', exact: true }).click();
  await expect(page.getByLabel('Step 1 title', { exact: true })).toHaveValue('Bake bread');
  await expect(page.locator('[data-guide-step]').nth(1)).not.toHaveAttribute('open', '');
  await expect(first).toHaveValue(/Bake\.\*\*bold text\*\*/);
  await expect(page.getByLabel('Step 2 duration', { exact: true })).toHaveValue('01:30:00');
  await page.reload();
  await expect(page.locator('[data-guide-step]').nth(1)).not.toHaveAttribute('open', '');
  await page.locator('[data-guide-step] summary').nth(1).focus();
  await page.keyboard.press('Enter');
  await expect(page.getByLabel('Step 2 title', { exact: true })).toBeVisible();
  await expect(page.getByLabel('Step 2 title', { exact: true })).toHaveValue('Mix ingredients');
  const duration = page.getByLabel('Step 2 duration', { exact: true });
  await duration.fill('00:00:00');
  await page.locator('[data-guide-step] summary').nth(1).click();
  await page.getByRole('button', { name: 'Save draft', exact: true }).click();
  await expect(duration).toBeVisible();
  await duration.fill('01:30:00');
  await page.getByRole('tab', { name: 'Tools', exact: true }).click();
  await expect(page.getByLabel('Tool 1 name (required to publish)', { exact: true })).toHaveValue('Mixing bowl');
  await page.getByRole('tab', { name: 'Materials', exact: true }).click();
  await expect(quantity).toHaveValue('10 boxes');
  await page.getByRole('tab', { name: 'Preview', exact: true }).click();
  await expect(page.frameLocator('#draft-preview').getByRole('heading', { name: 'Bake bread', exact: true })).toBeVisible();
  await expect(page.frameLocator('#draft-preview').getByText('1 hour, 30 minutes', { exact: true })).toBeVisible();
  await expect(page.frameLocator('#draft-preview').locator('main ol > li').nth(0).locator('img')).toHaveJSProperty('naturalWidth', 192);
  const anonymous = await browser.newContext({ baseURL: site.baseURL, ignoreHTTPSErrors: true, javaScriptEnabled: false });
  try {
    expect((await anonymous.request.get(mediaPath)).status()).toBe(404);
    const publicPath = await publish(page);
    const publicPage = await anonymous.newPage();
    await publicPage.goto(publicPath);
    await expect(publicPage.getByRole('heading', { name: 'Bake bread', exact: true })).toBeVisible();
    await expect(publicPage.getByRole('link', { name: 'Mixing bowl', exact: true })).toHaveAttribute('href', 'https://example.test/bowl');
    await expect(publicPage.getByRole('link', { name: '2 cups flour', exact: true })).toHaveAttribute('href', 'https://example.test/flour');
    await expect(publicPage.locator('main li').filter({ hasText: '2 cups flour' })).toContainText('10 boxes');
    await expect(publicPage.locator('main ol > li').nth(0).locator('strong')).toHaveText('bold text');
    await expect(publicPage.locator('main ol > li').nth(0).locator('img')).toHaveJSProperty('naturalWidth', 192);
    await expect(publicPage.locator('main time[datetime="PT5400S"]')).toHaveText('1 hour, 30 minutes');
    expect((await anonymous.request.get(mediaPath)).status()).toBe(200);
  } finally { await anonymous.close(); }
});

test.describe('guide forms without JavaScript', () => {
  test.use({ javaScriptEnabled: false });
  test('ordinary forms edit supplies, step Markdown and duration', async ({ owner: page, context }) => {
    await newPost(page, 'guide');
    await page.getByLabel('Title (required to publish)', { exact: true }).fill('Bread without JavaScript');
    await page.getByRole('button', { name: 'Add tool', exact: true }).click();
    await page.getByLabel('Tool 1 name (required to publish)', { exact: true }).fill('Bowl');
    await page.getByRole('button', { name: 'Add material', exact: true }).click();
    await page.getByLabel('Material 1 name (required to publish)', { exact: true }).fill('Flour');
    await page.getByLabel('Material 1 quantity', { exact: true }).fill('5 switches');
    await page.getByRole('button', { name: 'Add step', exact: true }).click();
    await page.getByLabel('Step 1 title', { exact: true }).fill('Mix ingredients');
    await page.locator('[data-guide-step] summary').click();
    await expect(page.getByLabel('Step 1 title', { exact: true })).toBeHidden();
    await page.locator('[data-guide-step] summary').click();
    await page.getByRole('textbox', { name: 'Step 1 instructions (required to publish)', exact: true }).fill('Mix **well**.');
    await page.getByLabel('Step 1 duration', { exact: true }).fill('00:00:30');
    await page.locator('[data-guide-step] summary').click();
    const publicPath = await publish(page);
    const publicPage = await context.newPage();
    await publicPage.goto(publicPath);
    await expect(publicPage.getByRole('heading', { name: 'Mix ingredients', exact: true })).toBeVisible();
    await expect(publicPage.getByText('Bowl', { exact: true })).toBeVisible();
    await expect(publicPage.getByText('Flour — 5 switches', { exact: true })).toBeVisible();
    await expect(publicPage.locator('main strong')).toHaveText('well');
    await expect(publicPage.locator('main time[datetime="PT30S"]')).toHaveText('30 seconds');
  });
});
